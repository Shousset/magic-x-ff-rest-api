export type TranslationKey = keyof typeof messages.es;

export function translate(
  locale: Locale,
  key: TranslationKey,
  values?: Record<string, string | number>,
): string {
  let message: string = messages[locale][key];
  for (const [name, value] of Object.entries(values ?? {})) {
    message = message.split(`{${name}}`).join(String(value));
  }
  return message;
}

export function resolveLocale(
  savedLocale: string | null,
  browserLocale: string | null,
): Locale {
  if (savedLocale === 'es' || savedLocale === 'en') {
    return savedLocale;
  }

  return browserLocale?.toLowerCase().startsWith('en') ? 'en' : 'es';
}

export function translateRarity(locale: Locale, rarity: string): string {
  if (locale === 'en') {
    return rarity.charAt(0).toUpperCase() + rarity.slice(1);
  }

  const spanishNames: Record<string, string> = {
    common: 'Común',
    uncommon: 'Poco común',
    rare: 'Rara',
    mythic: 'Mítica',
  };
  return spanishNames[rarity.toLowerCase()] ?? rarity;
}
